// TID Helper page: Ruby / Sapphire wild-encounter manipulation from the boot seed (gen3-enc.json).
//
// Ruby and Sapphire only, and that is a property of the games rather than a gap here. They seed the RNG
// once at boot from the RTC (pokeruby src/main.c:115) and nothing on the New Game or Continue path
// reseeds it, so the state at a given advance is arithmetic. On a dead battery the clock returns its
// dummy value every boot, giving the SAME seed 0x5A0 every time - which is what makes this repeatable.
// Emerald boots with seed 0 but its advance count is not its frame count; FireRed/LeafGreen reseed at the
// title screen from a sub-frame timer and cannot be aimed at all. Both are refused, with the reason.
//
// The encounter itself is generated by ShinyGenerators.gen3Wild (Gen 3 Wild "Method H"), which is the
// site's existing engine, line-cited to pret and following PokeFinder's frame convention and slot order.
// This page does not reimplement it.
//
// WHAT IS NOT DERIVED, and the page says so: the number of advances between a press a person can see and
// the frame the encounter is generated. It is per game, map and save, and only an emulator can measure it.
// So the advance offset is a CALIBRATION the runner resolves from one attempt, exactly as the R/S Trainer
// ID page resolves its own correction. Until they do, the table is "advance n gives this", not "press at
// this second". UMD: the pure part runs under node.
//
// The calibration itself - card 4, "What did you get?" - was missing until 2026-09-19. matchesFor was
// written and exported, the intro told the runner to "run the manip once, find what you got in the table",
// and nothing in the UI ever called it, so the one loop this page prescribes was the one thing it would not
// do. The panel converts an observed encounter into the advance(s) that generate it, stores the chosen
// advance as a per-game preference, and reads the table relative to it. It converts in one direction only:
// an encounter becomes an advance number. Nothing here turns an advance into a second, a frame count or a
// cue, because that is exactly the number this project has not measured for Ruby and Sapphire.
//
// core (rng.js) is here for NATURES, so the nature picker is the engine's own list rather than a second copy
// that can drift from the one the generator names a nature from.
